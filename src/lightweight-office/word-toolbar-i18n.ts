export function getWordToolbarTexts(language: LanguageCode): WordToolbarTexts {
  return WORD_TOOLBAR_TEXTS[language]
}

const disabledTooltipMarkers = new Set(
  Object.values(WORD_TOOLBAR_DISABLED_TEXTS).map((text) => `(${text})`),
)

function localizeDisabledTooltipMarkers(root: ParentNode, language: LanguageCode): void {
  const tooltipContents: Element[] = []
  if (root instanceof Element && root.matches('.sd-tooltip-content')) {
    tooltipContents.push(root)
  }
  tooltipContents.push(...root.querySelectorAll('.sd-tooltip-content'))

  const replacement = `(${WORD_TOOLBAR_DISABLED_TEXTS[language]})`
  for (const tooltip of tooltipContents) {
    for (const span of tooltip.querySelectorAll('span')) {
      if (disabledTooltipMarkers.has(span.textContent?.trim() ?? '')) {
        span.textContent = replacement
      }
    }
  }
}

/**
 * SuperDoc 1.44 appends a hard-coded English "(disabled)" marker after the
 * configured tooltip. Its tooltip is teleported to document.body, so localize
 * that one unsupported fragment as it is mounted.
 */
export function installWordToolbarTooltipLocalization(language: LanguageCode): () => void {
  if (typeof document === 'undefined' || !document.body) return () => undefined

  localizeDisabledTooltipMarkers(document.body, language)
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      for (const node of record.addedNodes) {
        if (node instanceof Element) localizeDisabledTooltipMarkers(node, language)
      }
    }
  })
  observer.observe(document.body, { childList: true, subtree: true })
  return () => observer.disconnect()
}
